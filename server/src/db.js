import Database from 'better-sqlite3';
import fs from 'node:fs';
import path from 'node:path';

const DEFAULT_DB_PATH = path.join(process.cwd(), 'data', 'call-booking.db');

// The single predefined calendar owner profile used by the admin part.
export const DEFAULT_OWNER = { id: 'owner', name: 'Kirill Mokevnin' };

// Seed event types so the booking flow works out of the box.
const DEFAULT_EVENT_TYPES = [
  {
    name: '30 Min Meeting',
    description: 'A quick call to get acquainted or discuss a focused topic.',
    durationMinutes: 30,
  },
  {
    name: '1 Hour Meeting',
    description: 'An hour-long session for a deeper discussion.',
    durationMinutes: 60,
  },
];

// Schema generated by AI Agent: event_types hold the meeting shapes; bookings
// store the occupied intervals. The UNIQUE(start_time) constraint plus the
// transaction-level overlap check enforce the global occupancy rule (two
// bookings may never overlap, even across event types).
export function createDb(dbPath = process.env.DB_PATH || DEFAULT_DB_PATH) {
  if (dbPath !== ':memory:') {
    fs.mkdirSync(path.dirname(dbPath), { recursive: true });
  }

  const db = new Database(dbPath);
  db.pragma('journal_mode = WAL');
  db.exec(`
    CREATE TABLE IF NOT EXISTS event_types (
      id               INTEGER PRIMARY KEY AUTOINCREMENT,
      name             TEXT NOT NULL,
      description      TEXT,
      duration_minutes INTEGER NOT NULL CHECK (duration_minutes > 0)
    );

    CREATE TABLE IF NOT EXISTS bookings (
      id            INTEGER PRIMARY KEY AUTOINCREMENT,
      event_type_id INTEGER NOT NULL REFERENCES event_types(id),
      start_time    TEXT NOT NULL,
      end_time      TEXT NOT NULL,
      name          TEXT NOT NULL,
      email         TEXT,
      created_at    TEXT NOT NULL,
      UNIQUE (start_time)
    );

    CREATE INDEX IF NOT EXISTS idx_bookings_overlap ON bookings (start_time, end_time);
  `);

  seed(db);
  return db;
}

function seed(db) {
  const { n } = db.prepare('SELECT COUNT(*) AS n FROM event_types').get();
  if (n === 0) {
    const insert = db.prepare(
      'INSERT INTO event_types (name, description, duration_minutes) VALUES (?, ?, ?)',
    );
    for (const eventType of DEFAULT_EVENT_TYPES) {
      insert.run(eventType.name, eventType.description, eventType.durationMinutes);
    }
  }
}
